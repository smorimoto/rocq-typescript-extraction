import { readFileSync } from "node:fs";
import path from "node:path";

const require_pattern = new RegExp(
  String.raw`(?:From\s+([\p{L}\p{N}_.]+)\s+)?Require\s+` +
    String.raw`(?:(?:Import|Export)\s+)?([\p{L}\p{N}_.\s]+?)\.(?=\s|$)`,
  "gu"
);

const comment_pattern = /\(\*(?:(?!\(\*|\*\)).)*\*\)/gsu;

const without_comments = (text: string): string => {
  let remaining = text;

  for (;;) {
    const stripped = remaining.replaceAll(comment_pattern, "");

    if (stripped === remaining) {
      return stripped;
    }

    remaining = stripped;
  }
};

const theory = (
  namespace: string,
  seen: Set<string>,
  requires: string
): string => {
  const prefix = `${namespace}.`;

  const modules = [...seen]
    .toSorted()
    .values()
    .filter((name) => name.startsWith(prefix))
    .map((name) => name.slice(prefix.length))
    .toArray()
    .join("\n");

  return `
(include_subdirs qualified)
(rocq.theory
 (name ${namespace})
 (modules ${modules})
 (theories ${requires}))
`;
};

export const generate_dune = (upstream: string): string => {
  const roots = new Map([
    ["Crypto", path.join(upstream, "src")],
    ["Rewriter", path.join(upstream, "rewriter/src/Rewriter")],
  ]);

  const seen = new Set<string>();

  const dependencies = (name: string): void => {
    if (seen.has(name)) {
      return;
    }

    const [namespace, ...parts] = name.split(".");

    if (namespace === undefined) {
      throw new Error("Missing dependency namespace");
    }

    const root = roots.get(namespace);

    if (root === undefined) {
      return;
    }

    const source = path.join(root, `${parts.join("/")}.v`);
    const text = without_comments(readFileSync(source, "utf-8"));
    seen.add(name);

    for (const [, prefix, names] of text.matchAll(require_pattern)) {
      if (names === undefined) {
        throw new Error("Missing Require modules");
      }

      for (const dependency of names.trim().split(/\s+/u)) {
        dependencies(prefix ? `${prefix}.${dependency}` : dependency);
      }
    }
  };

  dependencies("Crypto.Arithmetic.ModOps");

  return `; Generated by gen-dune.ts from the pinned upstream sources.
; Compile the dependency closure unchanged, including its proofs.

(subdir
 fiat-crypto
 (dirs src rewriter)
 (subdir
  rewriter
  (dirs src)
  (subdir
   src/Rewriter
   ${theory("Rewriter", seen, "Stdlib")}))
 (subdir
  src
  ${theory("Crypto", seen, "Stdlib Rewriter")}))
`;
};

if (import.meta.main) {
  const upstream = path.resolve(
    import.meta.dir,
    "../../submodules/fiat-crypto"
  );

  const result = Bun.spawnSync(["dune", "format-dune-file"], {
    stderr: "inherit",
    stdin: Buffer.from(generate_dune(upstream)),
    stdout: "inherit",
  });

  if (!result.success) {
    process.exit(result.exitCode || 1);
  }
}
