import { readFileSync } from "node:fs";
import path from "node:path";

const directories = ["lib", "common", "x86_64", "x86", "cfrontend", "flocq"];
const frontend = new Set(["Ctypes", "Cop", "Csyntax", "Csem", "Ctyping"]);

const require_pattern = new RegExp(
  String.raw`(?:From\s+([\p{L}\p{N}_.]+)\s+)?Require\s+` +
    String.raw`(?:(?:Import|Export)\s+)?([\p{L}\p{N}_.\s]+?)\.(?=\s|$)`,
  "gu"
);

const comment_pattern = /\(\*(?:(?!\(\*|\*\)).)*\*\)/gsu;

const without_comments = (text: string): string => {
  let remaining = text;

  for (;;) {
    const stripped = remaining.replaceAll(comment_pattern, "");

    if (stripped === remaining) {
      return stripped;
    }

    remaining = stripped;
  }
};

const is_lgpl = (file: string, text: string): boolean => {
  const [directory] = file.split(path.sep);
  const name = path.basename(file, ".v");

  const allowed =
    directory === "lib" ||
    directory === "common" ||
    directory === "flocq" ||
    (directory === "cfrontend" && frontend.has(name)) ||
    (directory === "x86_64" && name === "Archi") ||
    (directory === "x86" && name === "Builtins1");

  return allowed && text.slice(0, 2500).includes("GNU Lesser General Public");
};

export const generate_dune = (upstream: string): string => {
  const sources = new Map<string, string>();
  const glob = new Bun.Glob("**/*.v");

  for (const directory of directories) {
    const files = [...glob.scanSync(path.join(upstream, directory))].toSorted();

    for (const file of files) {
      const name = path.basename(file, ".v");

      if (sources.has(name)) {
        throw new Error(`Ambiguous module: ${name}`);
      }

      sources.set(name, path.join(directory, file));
    }
  }

  const seen = new Set<string>();

  const dependencies = (name: string): void => {
    const file = sources.get(name);

    if (file === undefined) {
      throw new Error(`Unknown CompCert module: ${name}`);
    }

    if (seen.has(file)) {
      return;
    }

    const text = readFileSync(path.join(upstream, file), "utf-8");

    if (!is_lgpl(file, text)) {
      throw new Error(`Not in the audited LGPL subset: ${file}`);
    }

    seen.add(file);

    for (const [, prefix, names] of without_comments(text).matchAll(
      require_pattern
    )) {
      if (names === undefined) {
        throw new Error("Missing Require modules");
      }

      if (prefix === "Coq" || prefix === "Stdlib" || prefix === "Corelib") {
        continue;
      }

      for (const dependency of names.trim().split(/\s+/u)) {
        dependencies(dependency.slice(dependency.lastIndexOf(".") + 1));
      }
    }
  };

  for (const entry of ["Ctyping", "Memory", "Globalenvs"]) {
    dependencies(entry);
  }

  const paths = [...seen].toSorted();
  const compcert: string[] = [];
  const flocq: string[] = [];

  for (const file of paths) {
    const parts = file.slice(0, -2).split(path.sep);

    if (parts[0] === "flocq") {
      flocq.push(parts.slice(1).join("."));
    } else {
      compcert.push(parts.join("."));
    }
  }

  const copies = directories
    .values()
    .filter((directory) => directory !== "flocq")
    .map((directory) => {
      const files = paths
        .values()
        .filter((file) => path.dirname(file) === directory)
        .map((file) => `(copy_files ../../${directory}/${path.basename(file)})`)
        .toArray();

      return `(subdir ${directory} ${files.join(" ")})`;
    })
    .toArray()
    .join("\n");

  return `; Generated by test/compcert/gen-dune.ts; only audited LGPL sources.
; x86-64 parameters are fixed independently of the host architecture.
(subdir compcert
 (dirs ${directories.join(" ")} selected)
 (subdir selected
  (include_subdirs qualified)
  ${copies}
  (rocq.theory
   (name compcert)
   (modules ${compcert.join(" ")})
   (flags :standard -w -deprecated,-register-all)
   (theories Stdlib Flocq)))
 (subdir flocq
  (include_subdirs qualified)
  (rocq.theory
   (name Flocq)
   (modules ${flocq.join(" ")})
   (flags :standard -w -deprecated)
   (theories Stdlib))))
`;
};

if (import.meta.main) {
  const upstream = path.resolve(import.meta.dir, "../../submodules/compcert");

  const result = Bun.spawnSync(["dune", "format-dune-file"], {
    stderr: "inherit",
    stdin: Buffer.from(generate_dune(upstream)),
    stdout: "inherit",
  });

  if (!result.success) {
    process.exit(result.exitCode || 1);
  }
}
